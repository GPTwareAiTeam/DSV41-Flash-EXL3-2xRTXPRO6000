"""Generate the mixed-K decode MoE header from a base coop kernel header.

Usage: mixedk_gen.py SRC_KERNEL_CUH OUT_CUH
Example: mixedk_gen.py exllamav3/exllamav3_ext/quant/exl3_moe_coop_kernel.cuh /tmp/mixed_kernel.cuh

Only the rates in CASES are instantiated; the host validates the tables against them.
"""
import sys
if len(sys.argv) < 3:
    sys.exit(__doc__)
SRC, OUT = sys.argv[1], sys.argv[2]
src = open(SRC).read().split('\n')

def kernel_body(name):
    # Locate a shared device body and return it through its column-zero closing brace.
    start = None
    for i, ln in enumerate(src):
        if ln.startswith(f'void {name}('):
            start = i
            break
    assert start is not None, name
    assert src[start - 1].startswith('__device__'), src[start - 1]
    assert src[start - 2].startswith('template <int bits, int cb, bool WIDE'), src[start - 2]
    end = next(j for j in range(start, len(src)) if src[j] == '}')
    return src[start + 1:end + 1]

A = kernel_body('moe_a_body')
B = kernel_body('moe_b_body')

# (k2, bits, half). k2 = 2*bits + half. mul1 rates 2, 2.5, 3, 3.5, 4 (routed) and 6 (shared expert, staged path)
CASES = [(4, 2, False), (5, 2, True), (6, 3, False), (7, 3, True), (8, 4, False), (12, 6, False)]

def gemv_lines(lines, macro, k2_expr):
    out = []
    for ln in lines:
        # sh_part must sit after the always-reserved staging region (mixed layout is rate-independent)
        ln = ln.replace('(tile_may_stage<bits, HALF>() ? WK * STAGE_WORDS : 0)', 'WK * STAGE_WORDS')
        if 'gemv_tile<bits, cb, WIDE, HALF>(' in ln:
            ln = ln.replace(f'gemv_tile<bits, cb, WIDE, HALF>(', f'{macro}({k2_expr}, ')
        out.append(ln)
    return out

L = []
L.append('#pragma once')
L.append('')
L.append('// GENERATED by qmesh/notes/mixedk_gen.py from exl3_moe_coop_kernel.cuh (working tree). Do not hand-edit.')
L.append('// Per-expert mixed-K decode A/B kernels: each block dispatches its GEMV tile on the expert rate')
L.append('// k2 = 2*bits + half from the per-projection table. Instantiated rates (mul1): '
         + ', '.join(f'{k/2:g}' for k, _, _ in CASES) + '.')
L.append('')
L.append('#include "exl3_moe_coop_kernel.cuh"')
L.append('')
L.append('namespace exl3_moe_coop_mixed_ns {')
L.append('using namespace exl3_moe_coop_ns;')
L.append('')
L.append('// Max staging/part layout across the instantiated cases: staging is always reserved, so the')
L.append('// layout does not depend on the expert rate')
L.append('constexpr int mixed_smem_a(int Hi) { return Hi * 2 + smem_red_bytes() + WK * STAGE_WORDS * 4; }')
L.append('constexpr int mixed_smem_b() { return smem_red_bytes() + WK * STAGE_WORDS * 4 + smem_part_bytes(); }')
L.append('')

# Per-case dispatch: one macro per projection that switches on k2 and calls gemv_tile with the case's
# (bits, half) for the kernel's cb and WIDE. Each case is a separate gemv_tile instance.
def dispatch(macro):
    d = [f'#define {macro}(k2, ...) \\', '    switch (k2) \\', '    { \\']
    for k2, bits, half in CASES:
        h = 'true' if half else 'false'
        d.append(f'        case {k2}: gemv_tile<{bits}, cb, WIDE, {h}>(__VA_ARGS__); break; \\')
    d.append('        default: __trap(); \\')
    d.append('    }')
    return d

L += dispatch('MIXED_GEMV_A')
L.append('')
L += dispatch('MIXED_GEMV_B')
L.append('')

def body(name, lines):
    return ['template <int cb, bool WIDE>', '__device__ __forceinline__',
            f'void {name}(const MoeCoopParams& p, int item, uint32_t* smem_dyn)'] + lines

L += body('mixed_a_body', gemv_lines(A, 'MIXED_GEMV_A', '(is_gate ? p.k2_g : p.k2_u)[local]'))
L.append('')
L += body('mixed_b_body', gemv_lines(B, 'MIXED_GEMV_B', 'p.k2_d[local]'))
L += r'''
template <int cb, bool WIDE>
__global__ __launch_bounds__(THREADS, MOE_COOP_MINB)
void exl3_moe_coop_a_mixed_kernel(const MoeCoopParams p)
{
    extern __shared__ uint32_t smem_dyn[];
    for (int i = blockIdx.x * THREADS + threadIdx.x; i < p.ctr_b_len; i += gridDim.x * THREADS)
        p.ctr_b[i] = 0;
    mixed_a_body<cb, WIDE>(p, blockIdx.x, smem_dyn);
}

template <int cb, bool WIDE>
__global__ __launch_bounds__(THREADS, MOE_COOP_MINB)
void exl3_moe_coop_b_mixed_kernel(const MoeCoopParams p)
{
    extern __shared__ uint32_t smem_dyn[];
    for (int i = blockIdx.x * THREADS + threadIdx.x; i < p.ctr_a_len; i += gridDim.x * THREADS)
        p.ctr_a[i] = 0;
    mixed_b_body<cb, WIDE>(p, blockIdx.x, smem_dyn);
}

template <bool WIDE_A, bool WIDE_B>
__global__ __launch_bounds__(THREADS, MOE_COOP_MINB)
void exl3_moe_coop_fused_mixed_kernel(const MoeCoopParams p)
{
    extern __shared__ uint32_t smem_dyn[];
    __shared__ int next_item;
    for (;;)
    {
        if (threadIdx.x == 0) next_item = atomicAdd(p.queue_head, 1);
        __syncthreads();
        if (next_item >= p.nA + p.nB) break;
        if (next_item < p.nA) mixed_a_body<2, WIDE_A>(p, next_item, smem_dyn);
        else mixed_b_body<2, WIDE_B>(p, next_item - p.nA, smem_dyn);
        __syncthreads();
    }
}
'''.splitlines()
L.append('')
L.append('}  // namespace exl3_moe_coop_mixed_ns')
open(OUT, 'w').write('\n'.join(L) + '\n')
print('wrote', OUT, len(L), 'lines')
