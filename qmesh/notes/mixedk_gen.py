# Generates exl3_moe_coop_mixed_kernel.cuh from the working-tree exl3_moe_coop_kernel.cuh (not HEAD).
# Mixed-K decode A/B kernels: the GEMV tile is dispatched per block on the expert's half-bit rate k2
# (2*bits + half). Only the rates in CASES are instantiated; the host validates the tables against them.
import sys
SRC = '/home/treadall/recipe-2xrtx-tp2-moe/exllamav3/exllamav3_ext/quant/exl3_moe_coop_kernel.cuh'
OUT = sys.argv[1] if len(sys.argv) > 1 else '/tmp/mk/mixed_kernel.cuh'
src = open(SRC).read().split('\n')

def kernel_body(name):
    # Locate a kernel by its signature (template head, __global__, void name(...)) and return its body
    # through the closing brace at column 0. Line numbers are not stable across edits.
    start = None
    for i, ln in enumerate(src):
        if ln.startswith(f'void {name}('):
            start = i
            break
    assert start is not None, name
    assert src[start - 1].startswith('__global__'), src[start - 1]
    assert src[start - 2].startswith('template <int bits, int cb, bool WIDE'), src[start - 3]
    end = next(j for j in range(start, len(src)) if src[j] == '}')
    return src[start + 1:end + 1]

A = kernel_body('exl3_moe_coop_a_kernel')
B = kernel_body('exl3_moe_coop_b_kernel')

# (k2, bits, half). k2 = 2*bits + half. mul1 rates 2, 2.5, 3, 3.5, 4 (routed) and 6 (shared expert, staged path)
CASES = [(4, 2, False), (5, 2, True), (6, 3, False), (7, 3, True), (8, 4, False), (12, 6, False)]

def gemv_lines(lines, macro, k2_expr):
    out = []
    for ln in lines:
        # sh_part must sit after the always-reserved staging region (mixed layout is rate-independent)
        ln = ln.replace('(tile_may_stage<bits, HALF>() ? WK * STAGE_WORDS : 0)', 'WK * STAGE_WORDS')
        if 'gemv_tile<bits, cb, WIDE, HALF>(' in ln:
            ln = ln.replace(f'gemv_tile<bits, cb, WIDE, HALF>(', f'{macro}({k2_expr}, ')
        out.append(ln)
    return out

L = []
L.append('#pragma once')
L.append('')
L.append('// GENERATED by qmesh/notes/mixedk_gen.py from exl3_moe_coop_kernel.cuh (working tree). Do not hand-edit.')
L.append('// Per-expert mixed-K decode A/B kernels: each block dispatches its GEMV tile on the expert rate')
L.append('// k2 = 2*bits + half from the per-projection table. Instantiated rates (mul1): '
         + ', '.join(f'{k/2:g}' for k, _, _ in CASES) + '.')
L.append('')
L.append('#include "exl3_moe_coop_kernel.cuh"')
L.append('')
L.append('namespace exl3_moe_coop_mixed_ns {')
L.append('using namespace exl3_moe_coop_ns;')
L.append('')
L.append('// Max staging/part layout across the instantiated cases: staging is always reserved, so the')
L.append('// layout does not depend on the expert rate')
L.append('constexpr int mixed_smem_a(int Hi) { return Hi * 2 + smem_red_bytes() + WK * STAGE_WORDS * 4; }')
L.append('constexpr int mixed_smem_b() { return smem_red_bytes() + WK * STAGE_WORDS * 4 + smem_part_bytes(); }')
L.append('')

# Per-case dispatch: one macro per projection that switches on k2 and calls gemv_tile with the case's
# (bits, half) for the kernel's cb and WIDE. Each case is a separate gemv_tile instance.
def dispatch(macro):
    d = [f'#define {macro}(k2, ...) \\', '    switch (k2) \\', '    { \\']
    for k2, bits, half in CASES:
        h = 'true' if half else 'false'
        d.append(f'        case {k2}: gemv_tile<{bits}, cb, WIDE, {h}>(__VA_ARGS__); break; \\')
    d.append('        default: __trap(); \\')
    d.append('    }')
    return d

L += dispatch('MIXED_GEMV_A')
L.append('')
L += dispatch('MIXED_GEMV_B')
L.append('')

def kernel(name, lines):
    out = ['template <int cb, bool WIDE>', '__global__ __launch_bounds__(THREADS, MOE_COOP_MINB)', f'void {name}(const MoeCoopParams p)']
    return out + lines

L += kernel('exl3_moe_coop_a_mixed_kernel', gemv_lines(A, 'MIXED_GEMV_A', '(is_gate ? p.k2_g : p.k2_u)[local]'))
L.append('')
L += kernel('exl3_moe_coop_b_mixed_kernel', gemv_lines(B, 'MIXED_GEMV_B', 'p.k2_d[local]'))
L.append('')
L.append('}  // namespace exl3_moe_coop_mixed_ns')
open(OUT, 'w').write('\n'.join(L) + '\n')
print('wrote', OUT, len(L), 'lines')
